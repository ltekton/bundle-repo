#!/usr/bin/env python3
"""Generate RFC/product -> implementation -> pytest traceability."""

from __future__ import annotations

import argparse
import ast
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
ID_RE = re.compile(
    r"\bBR-(?:P|G|NG|REQ|SI|ADR|FMT|PATH|MAN|PART|REC|VERIFY|RECON|ERR)(?:-[A-Z0-9]+)*-\d{3}\b"
)
DEF_RE = re.compile(
    r"(?:^|\n)(?:#{1,6}\s+|[-*]\s+\*\*)?(BR-(?:P|G|NG|REQ|SI|ADR|FMT|PATH|MAN|PART|REC|VERIFY|RECON|ERR)(?:-[A-Z0-9]+)*-\d{3})"
)


def definitions() -> tuple[dict[str, list[str]], list[str]]:
    found: dict[str, list[str]] = defaultdict(list)
    for path in sorted(DOCS.glob("*.md")):
        text = path.read_text("utf-8")
        for rid in DEF_RE.findall(text):
            found[rid].append(str(path.relative_to(ROOT)))
    duplicates = [rid for rid, paths in found.items() if len(paths) > 1]
    return dict(found), duplicates


def source_refs() -> dict[str, list[str]]:
    refs: dict[str, list[str]] = defaultdict(list)
    for path in [ROOT / "bundle_repo.py", *sorted((ROOT / "scripts").glob("*.py"))]:
        if not path.exists():
            continue
        for rid in set(ID_RE.findall(path.read_text("utf-8"))):
            refs[rid].append(str(path.relative_to(ROOT)))
    return dict(refs)


def test_refs() -> tuple[dict[str, list[str]], list[str]]:
    refs: dict[str, list[str]] = defaultdict(list)
    invalid: list[str] = []
    for path in sorted((ROOT / "tests").rglob("test_*.py")):
        tree = ast.parse(path.read_text("utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if not isinstance(
                node, (ast.FunctionDef, ast.AsyncFunctionDef)
            ) or not node.name.startswith("test_"):
                continue
            nodeid = f"{path.relative_to(ROOT)}::{node.name}"
            for decorator in node.decorator_list:
                if not isinstance(decorator, ast.Call):
                    continue
                func = ast.unparse(decorator.func)
                if func not in {"pytest.mark.req", "mark.req"}:
                    continue
                for arg in decorator.args:
                    if (
                        not isinstance(arg, ast.Constant)
                        or not isinstance(arg.value, str)
                        or not ID_RE.fullmatch(arg.value)
                    ):
                        invalid.append(f"{nodeid}: invalid req marker argument")
                    else:
                        refs[arg.value].append(nodeid)
    return dict(refs), invalid


def render() -> tuple[str, bool]:
    defined, duplicates = definitions()
    implementation = source_refs()
    tests, invalid = test_refs()
    known = set(defined)
    unknown = (set(implementation) | set(tests)) - known
    rows = [
        "# Traceability Matrix",
        "",
        "Generated by `scripts/traceability.py`.",
        "",
        "| Requirement | Specification | Implementation | Tests | Status |",
        "|---|---|---|---|---|",
    ]
    failed = bool(duplicates or unknown or invalid)
    for rid in sorted(known):
        impl = implementation.get(rid, [])
        covered = tests.get(rid, [])
        status = (
            "COVERED"
            if impl and covered
            else "MISSING IMPLEMENTATION"
            if not impl
            else "MISSING TEST"
        )
        # Missing links remain visible in the generated matrix. Structural check mode
        # fails only for duplicate definitions, unknown IDs, or malformed markers.
        rows.append(
            f"| {rid} | {', '.join(defined[rid])} | {', '.join(impl) or '—'} | {', '.join(covered) or '—'} | {status} |"
        )
    if duplicates or unknown or invalid:
        rows += ["", "## Errors"]
        rows += [f"- Duplicate definition: {x}" for x in duplicates]
        rows += [f"- Unknown reference: {x}" for x in sorted(unknown)]
        rows += [f"- {x}" for x in invalid]
    return "\n".join(rows) + "\n", failed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    report, failed = render()
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(report, "utf-8")
    elif args.json:
        print(json.dumps({"ok": not failed, "report": report}))
    else:
        print(report, end="")
    return 1 if args.check and failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
